-- 0001: esquema completo del CRM (antes prospects.db + platform.db en SQLite).
-- Sin calificar el schema: el runner fija search_path (crm o crm_test_*).
-- Tipos: texto ISO -> timestamptz, 0/1 -> boolean (tablas CRM),
-- INTEGER PRIMARY KEY -> bigint identity BY DEFAULT (la importación conserva ids).
-- Las tablas de plataforma conservan epoch en BIGINT como en SQLite.

-- ---------------------------------------------------------------- CRM

CREATE TABLE prospects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    address TEXT DEFAULT '',
    city TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    website TEXT DEFAULT '',
    rating DOUBLE PRECISION DEFAULT 0,
    -- NULL = desconocido (la importación anula valores > 50 000, ver D9).
    reviews_count INTEGER DEFAULT 0,
    maps_url TEXT DEFAULT '',
    latitude DOUBLE PRECISION DEFAULT 0,
    longitude DOUBLE PRECISION DEFAULT 0,
    instagram_url TEXT DEFAULT '',
    instagram_handle TEXT DEFAULT '',
    ig_followers INTEGER DEFAULT 0,
    ig_bio TEXT DEFAULT '',
    ig_email TEXT DEFAULT '',
    ig_phone TEXT DEFAULT '',
    ig_website TEXT DEFAULT '',
    demo_url TEXT DEFAULT '',
    demo_rating DOUBLE PRECISION DEFAULT 0,
    -- Solo captura de la demo. Las fotos del negocio van en business_photo_*.
    screenshot_path TEXT DEFAULT '',
    lovable_account_used TEXT DEFAULT '',
    prompt_used TEXT DEFAULT '',
    lovable_prompt TEXT DEFAULT '',
    whatsapp_message TEXT DEFAULT '',
    status TEXT NOT NULL DEFAULT 'scraped',
    scraped_at TIMESTAMPTZ DEFAULT now(),
    contacted_at TIMESTAMPTZ,
    is_contacted BOOLEAN NOT NULL DEFAULT false,
    notes TEXT DEFAULT '',
    -- photos-plan §4 / Module 2 Phase 1
    google_place_id TEXT,
    business_photo_path TEXT,
    business_photo_source TEXT CHECK (
        business_photo_source IS NULL
        OR business_photo_source IN ('places_api', 'maps_scrape', 'instagram', 'streetview', 'manual')
    ),
    business_photo_fetched_at TIMESTAMPTZ,
    business_photo_attribution JSONB,
    legacy_photo_url TEXT,
    UNIQUE (name, address)
);

CREATE INDEX prospects_status_idx ON prospects (status);
CREATE INDEX prospects_category_idx ON prospects (category);
CREATE INDEX prospects_scraped_at_idx ON prospects (scraped_at DESC);
CREATE INDEX prospects_google_place_id_idx ON prospects (google_place_id)
    WHERE google_place_id IS NOT NULL;

CREATE TABLE category_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    icon TEXT DEFAULT ''
);

