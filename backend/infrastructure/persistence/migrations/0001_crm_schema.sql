    prospect_id BIGINT UNIQUE REFERENCES prospects (id) ON DELETE SET NULL,
    display_name TEXT NOT NULL,
    category TEXT DEFAULT '',
    contact_email TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    stage TEXT NOT NULL DEFAULT 'quote_sent',
    quote_amount DOUBLE PRECISION,
