CREATE INDEX clients_stage_idx ON clients (stage);

CREATE TABLE client_meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients (id) ON DELETE CASCADE,
    title TEXT DEFAULT '',
