-- ------------------------------------------- RLS, roles y privilegios
-- RLS sin políticas para anon/authenticated: segundo candado aunque alguien
-- exponga el schema en la Data API. El dueño (crm_app) no está sujeto a RLS.
-- crm_readonly: SELECT en todo (consola SQL). crm_ingest: scripts locales,
-- SELECT/INSERT/UPDATE solo en prospects y category_catalog, sin DELETE.

DO $$
DECLARE
    tbl text;
    has_readonly boolean := EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_readonly');
    has_ingest boolean := EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_ingest');
BEGIN
    FOR tbl IN
        SELECT c.relname FROM pg_class c
        WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind = 'r'
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
        EXECUTE format('REVOKE ALL ON TABLE %I FROM PUBLIC', tbl);
        IF has_readonly THEN
            EXECUTE format('GRANT SELECT ON TABLE %I TO crm_readonly', tbl);
            EXECUTE format(
                'CREATE POLICY crm_readonly_select ON %I FOR SELECT TO crm_readonly USING (true)', tbl);
        END IF;
    END LOOP;

    IF has_readonly THEN
        EXECUTE format('GRANT USAGE ON SCHEMA %I TO crm_readonly', current_schema());
    END IF;

    IF has_ingest THEN
        EXECUTE format('GRANT USAGE ON SCHEMA %I TO crm_ingest', current_schema());
        FOREACH tbl IN ARRAY ARRAY['prospects', 'category_catalog'] LOOP
            EXECUTE format('GRANT SELECT, INSERT, UPDATE ON TABLE %I TO crm_ingest', tbl);
            EXECUTE format('GRANT USAGE ON SEQUENCE %I TO crm_ingest', tbl || '_id_seq');
            EXECUTE format(
                'CREATE POLICY crm_ingest_select ON %I FOR SELECT TO crm_ingest USING (true)', tbl);
            EXECUTE format(
                'CREATE POLICY crm_ingest_insert ON %I FOR INSERT TO crm_ingest WITH CHECK (true)', tbl);
            EXECUTE format(
                'CREATE POLICY crm_ingest_update ON %I FOR UPDATE TO crm_ingest USING (true) WITH CHECK (true)', tbl);
        END LOOP;
    END IF;
END $$;
